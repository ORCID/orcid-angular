import { SecurityContext } from '@angular/core'
import { TestBed } from '@angular/core/testing'
import { DomSanitizer } from '@angular/platform-browser'

import { Video } from '../../../types/homepage-content.v2'
import {
  aspectRatioCss,
  isPlayable,
  playerEmbedUrl,
  providerLabel,
  providerSite,
  trustedPlayerUrl,
  watchUrl,
} from './player-url'

/** The two videos the live homepage actually publishes. */
function video(overrides: Partial<Video> = {}): Video {
  return {
    provider: 'vimeo',
    videoId: '1198760040',
    title: 'What is ORCID?',
    poster: { src: '/assets/img/poster.jpg', alt: 'A researcher at a laptop' },
    captions: { available: true, locales: ['en'], autoGenerated: false },
    audioDescription: { status: 'described-track' },
    transcript: 'A transcript.',
    ...overrides,
  }
}

describe('the video player URL', () => {
  it('builds the Vimeo embed URL for a real Vimeo id', () => {
    expect(playerEmbedUrl(video(), { autoplay: true })).toBe(
      'https://player.vimeo.com/video/1198760040?dnt=1&title=0&autoplay=1'
    )
  })

  it('builds the YouTube embed URL for a real YouTube id', () => {
    expect(
      playerEmbedUrl(video({ provider: 'youtube', videoId: '1rZvFGLe7bg' }), {
        autoplay: true,
      })
    ).toBe(
      'https://www.youtube-nocookie.com/embed/1rZvFGLe7bg' +
        '?rel=0&modestbranding=1&cc_load_policy=1&autoplay=1'
    )
  })

  it('leaves autoplay off unless the caller is answering a click', () => {
    expect(playerEmbedUrl(video())).toContain('autoplay=0')
    expect(
      playerEmbedUrl(video({ provider: 'youtube', videoId: '1rZvFGLe7bg' }))
    ).toContain('autoplay=0')
  })

  it('applies a start offset the way each provider expects', () => {
    expect(playerEmbedUrl(video({ startAt: 42 }), { autoplay: true })).toBe(
      'https://player.vimeo.com/video/1198760040?dnt=1&title=0&autoplay=1#t=42s'
    )
    expect(
      playerEmbedUrl(
        video({ provider: 'youtube', videoId: '1rZvFGLe7bg', startAt: 42 }),
        { autoplay: true }
      )
    ).toContain('&autoplay=1&start=42')
  })

  it('ignores a start offset that is not a whole number of seconds', () => {
    expect(playerEmbedUrl(video({ startAt: 1.5 }))).not.toContain('#t=')
    expect(playerEmbedUrl(video({ startAt: -3 }))).not.toContain('#t=')
  })

  it('builds nothing for an id the provider pattern rejects', () => {
    expect(playerEmbedUrl(video({ videoId: 'not-a-vimeo-id' }))).toBeNull()
    expect(
      playerEmbedUrl(video({ provider: 'youtube', videoId: 'too-short' }))
    ).toBeNull()
    expect(playerEmbedUrl(video({ videoId: '1198760040/../evil' }))).toBeNull()
    expect(isPlayable(video({ videoId: '' }))).toBe(false)
  })

  it('builds nothing for a provider this build does not know', () => {
    const unknown = video({ provider: 'dailymotion' as Video['provider'] })
    expect(playerEmbedUrl(unknown)).toBeNull()
    expect(watchUrl(unknown)).toBeNull()
    expect(providerLabel(unknown)).toBeNull()
  })

  it('does not answer for an inherited object property', () => {
    expect(
      playerEmbedUrl(video({ provider: 'constructor' as Video['provider'] }))
    ).toBeNull()
  })

  it('always offers the video on the provider own site', () => {
    expect(watchUrl(video())).toBe('https://vimeo.com/1198760040')
    expect(
      watchUrl(video({ provider: 'youtube', videoId: '1rZvFGLe7bg' }))
    ).toBe('https://www.youtube.com/watch?v=1rZvFGLe7bg')
    expect(providerLabel(video())).toBe('Vimeo')
    expect(
      providerSite(video({ provider: 'youtube', videoId: '1rZvFGLe7bg' }))
    ).toBe('youtube.com')
  })

  it('gives a frame a real shape, 16:9 unless the editor chose otherwise', () => {
    expect(aspectRatioCss(undefined)).toBe('16 / 9')
    expect(aspectRatioCss('9:16')).toBe('9 / 16')
    expect(aspectRatioCss('4:3')).toBe('4 / 3')
  })

  describe('as a value a template can bind', () => {
    let sanitizer: DomSanitizer

    beforeEach(() => {
      TestBed.configureTestingModule({})
      sanitizer = TestBed.inject(DomSanitizer)
    })

    it('survives the sanitiser unchanged for a valid id', () => {
      const trusted = trustedPlayerUrl(video(), sanitizer, { autoplay: true })
      expect(sanitizer.sanitize(SecurityContext.RESOURCE_URL, trusted)).toBe(
        'https://player.vimeo.com/video/1198760040?dnt=1&title=0&autoplay=1'
      )
    })

    it('is null for a bad id, so nothing is ever trusted by accident', () => {
      expect(
        trustedPlayerUrl(video({ videoId: 'javascript:alert(1)' }), sanitizer)
      ).toBeNull()
    })
  })
})
