import { ComponentFixture, TestBed } from '@angular/core/testing'

import { Video } from '../../../types/homepage-content.v2'
import { VideoConsentComponent } from './video-consent.component'

function video(overrides: Partial<Video> = {}): Video {
  return {
    provider: 'vimeo',
    videoId: '1198760040',
    title: 'What is ORCID?',
    poster: { src: '/assets/img/poster.jpg', alt: 'A researcher at a laptop' },
    captions: { available: true, locales: ['en'], autoGenerated: false },
    audioDescription: { status: 'described-track' },
    transcript: 'ORCID gives you a persistent identifier.',
    ...overrides,
  }
}

describe('the video consent state', () => {
  let fixture: ComponentFixture<VideoConsentComponent>
  let element: HTMLElement

  function render(
    input: Video = video(),
    canOpenPreferences = false
  ): HTMLElement {
    fixture.componentRef.setInput('video', input)
    fixture.componentRef.setInput('canOpenPreferences', canOpenPreferences)
    fixture.detectChanges()
    return fixture.nativeElement as HTMLElement
  }

  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [VideoConsentComponent],
    }).compileComponents()

    fixture = TestBed.createComponent(VideoConsentComponent)
    element = fixture.nativeElement as HTMLElement
  })

  it('still shows the poster, with the alt text the editor wrote', () => {
    const image = render().querySelector('img') as HTMLImageElement
    expect(image.getAttribute('alt')).toBe('A researcher at a laptop')
    expect(image.getAttribute('src')).toBe('/assets/img/poster.jpg')
  })

  it('says which site hosts the video and why it is not playing here', () => {
    expect(render().textContent).toContain(
      'This video is hosted by Vimeo. Playing it here needs functional cookies.'
    )
  })

  it('names the site without pretending to know an unknown provider', () => {
    const text = render(
      video({ provider: 'dailymotion' as Video['provider'] })
    ).textContent
    expect(text).toContain('Playing this video here needs functional cookies.')
    expect(text).not.toContain('hosted by')
  })

  it('always offers the video on the provider own site, in a new tab', () => {
    const link = render().querySelector('a') as HTMLAnchorElement
    expect(link.getAttribute('href')).toBe('https://vimeo.com/1198760040')
    expect(link.getAttribute('target')).toBe('_blank')
    expect(link.getAttribute('rel')).toBe('noopener noreferrer')
    expect(link.textContent?.trim()).toBe(
      'Watch on vimeo.com (opens in a new tab)'
    )
  })

  it('sends a YouTube visitor to YouTube', () => {
    const link = render(
      video({ provider: 'youtube', videoId: '1rZvFGLe7bg' })
    ).querySelector('a') as HTMLAnchorElement
    expect(link.getAttribute('href')).toBe(
      'https://www.youtube.com/watch?v=1rZvFGLe7bg'
    )
  })

  it('offers no cookie settings when there is no preference centre to open', () => {
    expect(render().querySelector('button')).toBeNull()
  })

  it('asks the host to open the preference centre when one exists', () => {
    const opened = jasmine.createSpy('allow')
    fixture.componentInstance.allow.subscribe(opened)

    const button = render(video(), true).querySelector(
      'button'
    ) as HTMLButtonElement
    expect(button.getAttribute('type')).toBe('button')
    button.click()

    expect(opened).toHaveBeenCalled()
  })
})
