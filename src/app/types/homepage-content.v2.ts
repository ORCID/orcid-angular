/**
 * The homepage content contract, schema version 2.
 *
 * These types mirror `schema/catalogue.json` in orcid-homepage-decap-cms, which
 * is the single source of truth for section types, their fields and their
 * variants. The published bundle generates an equivalent file; this hand-written
 * copy is what the renderer compiles against until the generated one is
 * vendored, and `catalogue-coverage.spec.ts` asserts the two agree.
 *
 * Version 1 was a fixed page: a hero, some news and a closing section. Version 2
 * is a list of sections an editor composes, each with a type and a variant that
 * chooses how it displays. Nothing here carries a heading level, a colour or a
 * width: those are computed by the renderer from position and type, so a
 * careless edit cannot produce an inaccessible page.
 */

export const HOMEPAGE_CONTENT_SCHEMA_MAJOR = 2

/** Majors this build can render. Version 1 is read through an adapter. */
export const SUPPORTED_SCHEMA_MAJORS: readonly number[] = [1, 2]

// ---------------------------------------------------------------------------
// Shared value objects
// ---------------------------------------------------------------------------

export type Span = 'full' | 'half'
export type Spacing = 'compact' | 'normal' | 'loose'
export type Tone = 'default' | 'surface' | 'brand-dark' | 'brand-tint'
export type FocalPoint = 'center' | 'top' | 'bottom' | 'start' | 'end'
export type AspectRatio = '16:9' | '4:3' | '1:1' | '9:16'
export type ActionStyle = 'primary' | 'secondary'
export type VideoProvider = 'vimeo' | 'youtube'

export interface SectionLayout {
  span: Span
  spacing: Spacing
  tone: Tone
}

/** An image that carries no meaning; the renderer always hides it from readers. */
export interface DecorativeImage {
  src: string
  focalPoint?: FocalPoint
}

/** An image that carries meaning; `alt` is required by the schema. */
export interface InformativeImage {
  src: string
  alt: string
  focalPoint?: FocalPoint
  containsText?: boolean
}

export interface Link {
  label: string
  href: string
}

export interface Action {
  id: string
  label: string
  href: string
  style: ActionStyle
}

export interface FeatureItem {
  id: string
  title?: string
  body: string
  icon?: DecorativeImage
  link?: Link
}

export interface Audience {
  id: string
  label: string
  intro: string
  background?: DecorativeImage
  features: FeatureItem[]
}

export interface LinkItem {
  id: string
  label: string
  href: string
  description?: string
  icon?: DecorativeImage
}

export interface Captions {
  available: true
  locales: string[]
  autoGenerated?: boolean
}

export interface AudioDescription {
  status: 'described-track' | 'not-needed'
  justification?: string
}

/**
 * Everything needed to publish a video accessibly. The accessibility fields are
 * required by the schema rather than encouraged in a guideline, because a video
 * without captions or a transcript is one nobody can fix after publication.
 */
export interface Video {
  provider: VideoProvider
  videoId: string
  title: string
  aspectRatio?: AspectRatio
  durationSeconds?: number
  startAt?: number
  poster: InformativeImage
  captions: Captions
  audioDescription: AudioDescription
  transcript: string
}

// ---------------------------------------------------------------------------
// Sections
// ---------------------------------------------------------------------------

interface SectionBase<TType extends string, TVariant extends string> {
  id: string
  type: TType
  variant: TVariant
  layout: SectionLayout
}

export type AudienceSelectorVariant = 'tabs-photo' | 'tabs-flat' | 'stacked'

export interface AudienceSelectorSection
  extends SectionBase<'audience-selector', AudienceSelectorVariant> {
  title?: string
  audiences: Audience[]
}

export type MediaVariant = 'media-end' | 'media-below' | 'media-only'

export interface MediaSection extends SectionBase<'media', MediaVariant> {
  kicker?: string
  title?: string
  body?: string
  mediaKind: 'video' | 'image'
  video?: Video
  image?: InformativeImage
  actions?: Action[]
}

export type FeatureListVariant = 'cards' | 'columns' | 'panel' | 'checklist'

export interface FeatureListSection
  extends SectionBase<'feature-list', FeatureListVariant> {
  title?: string
  intro?: string
  columns?: 2 | 3
  items: FeatureItem[]
}

export type QuickLinksVariant = 'bar' | 'grid' | 'list'

export interface QuickLinksSection
  extends SectionBase<'quick-links', QuickLinksVariant> {
  title: string
  titleHidden?: boolean
  links: LinkItem[]
}

export type ProseVariant = 'default' | 'lead' | 'centered'

export interface ProseSection extends SectionBase<'prose', ProseVariant> {
  title?: string
  body: string
}

export type CtaBandVariant = 'band' | 'panel' | 'inline'

export interface CtaBandSection extends SectionBase<'cta-band', CtaBandVariant> {
  title: string
  body?: string
  actions: Action[]
}

export type NewsFeedVariant = 'grid' | 'list'

export interface NewsFeedSection
  extends SectionBase<'news-feed', NewsFeedVariant> {
  title: string
  source: 'orcid-blog'
  maxItems?: number
}

export type HomepageSection =
  | AudienceSelectorSection
  | MediaSection
  | FeatureListSection
  | QuickLinksSection
  | ProseSection
  | CtaBandSection
  | NewsFeedSection

export type HomepageSectionType = HomepageSection['type']

export const SECTION_TYPES = [
  'audience-selector',
  'media',
  'feature-list',
  'quick-links',
  'prose',
  'cta-band',
  'news-feed',
] as const

export const VARIANTS: Record<HomepageSectionType, readonly string[]> = {
  'audience-selector': ['tabs-photo', 'tabs-flat', 'stacked'],
  media: ['media-end', 'media-below', 'media-only'],
  'feature-list': ['cards', 'columns', 'panel', 'checklist'],
  'quick-links': ['bar', 'grid', 'list'],
  prose: ['default', 'lead', 'centered'],
  'cta-band': ['band', 'panel', 'inline'],
  'news-feed': ['grid', 'list'],
}

// ---------------------------------------------------------------------------
// Document
// ---------------------------------------------------------------------------

export interface HomepagePage {
  /** The only h1 on the page. Every section heading sits under it. */
  title: string
  description: string
}

export interface HomepageContentMeta {
  locale: string
  version: string
  commit: string
  generatedAt: string
  translated: number
  total: number
  untranslated?: string[]
}

export interface HomepageContent {
  schemaVersion: number
  catalogueVersion?: number
  meta?: HomepageContentMeta
  page: HomepagePage
  sections: HomepageSection[]
}

// ---------------------------------------------------------------------------
// Guards
// ---------------------------------------------------------------------------

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function isNonEmptyString(value: unknown): value is string {
  return typeof value === 'string' && value.length > 0
}

export function isSectionType(value: unknown): value is HomepageSectionType {
  return (
    typeof value === 'string' &&
    (SECTION_TYPES as readonly string[]).includes(value)
  )
}

/**
 * Whether one section is renderable by this build.
 *
 * Deliberately per-section: an unknown type or a malformed section is dropped
 * on its own rather than taking the page down with it, which is what lets the
 * content repository add a section type without waiting for a renderer release.
 */
export function isRenderableSection(value: unknown): value is HomepageSection {
  if (!isObject(value)) return false
  if (!isNonEmptyString(value['id'])) return false
  if (!isSectionType(value['type'])) return false
  if (!isNonEmptyString(value['variant'])) return false

  const layout = value['layout']
  if (!isObject(layout)) return false

  switch (value['type']) {
    case 'audience-selector':
      return (
        Array.isArray(value['audiences']) &&
        value['audiences'].length > 0 &&
        value['audiences'].every(
          (a: unknown) =>
            isObject(a) &&
            isNonEmptyString(a['id']) &&
            isNonEmptyString(a['label']) &&
            isNonEmptyString(a['intro']) &&
            Array.isArray(a['features'])
        )
      )
    case 'media':
      return value['mediaKind'] === 'video'
        ? isObject(value['video'])
        : isObject(value['image'])
    case 'feature-list':
      return (
        Array.isArray(value['items']) &&
        value['items'].length > 0 &&
        value['items'].every(
          (i: unknown) => isObject(i) && isNonEmptyString(i['body'])
        )
      )
    case 'quick-links':
      return (
        isNonEmptyString(value['title']) &&
        Array.isArray(value['links']) &&
        value['links'].length > 0
      )
    case 'prose':
      return isNonEmptyString(value['body'])
    case 'cta-band':
      return (
        isNonEmptyString(value['title']) &&
        Array.isArray(value['actions']) &&
        value['actions'].length > 0
      )
    case 'news-feed':
      return isNonEmptyString(value['title'])
    default:
      return false
  }
}

/**
 * Whether a fetched document is one this build can render at all.
 *
 * Only the page-level shape is checked here. Sections are validated one by one
 * so that a single bad section costs its own block, not the whole homepage.
 */
export function isSupportedHomepageContent(
  value: unknown
): value is HomepageContent {
  if (!isObject(value)) return false

  const version = value['schemaVersion']
  if (
    typeof version !== 'number' ||
    !Number.isInteger(version) ||
    !SUPPORTED_SCHEMA_MAJORS.includes(version)
  ) {
    return false
  }

  const page = value['page']
  return (
    isObject(page) &&
    isNonEmptyString(page['title']) &&
    Array.isArray(value['sections'])
  )
}
