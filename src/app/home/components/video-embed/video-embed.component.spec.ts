import { ComponentFixture, TestBed } from '@angular/core/testing'

import { Video } from '../../../types/homepage-content.v2'
import { VideoEmbedComponent } from './video-embed.component'

interface OneTrustTestWindow extends Window {
  OnetrustActiveGroups?: string
  OneTrust?: { ToggleInfoDisplay?: () => void }
}

const testWindow = window as OneTrustTestWindow

function video(overrides: Partial<Video> = {}): Video {
  return {
    provider: 'vimeo',
    videoId: '1198760040',
    title: 'What is ORCID?',
    poster: { src: '/assets/img/poster.jpg', alt: 'A researcher at a laptop' },
    captions: { available: true, locales: ['en'], autoGenerated: false },
    audioDescription: { status: 'described-track' },
    transcript:
      'ORCID gives every researcher a persistent identifier.\n\n' +
      'It stays with them for their whole career.',
    ...overrides,
  }
}

/** What OneTrust writes on the window once functional cookies are accepted. */
function acceptFunctionalCookies(): void {
  testWindow.OnetrustActiveGroups = ',C0001,C0002,C0003,C0004,'
}

describe('a homepage video', () => {
  let fixture: ComponentFixture<VideoEmbedComponent>

  function render(input: Video = video()): HTMLElement {
    fixture.componentRef.setInput('video', input)
    fixture.detectChanges()
    return fixture.nativeElement as HTMLElement
  }

  function transcriptText(element: HTMLElement): string {
    const region = element.querySelector('.disclosure-region') as HTMLElement
    return region.textContent ?? ''
  }

  function openTranscript(element: HTMLElement): HTMLElement {
    const toggle = element.querySelector(
      '.disclosure-toggle'
    ) as HTMLButtonElement
    toggle.click()
    fixture.detectChanges()
    return element
  }

  beforeEach(async () => {
    delete testWindow.OnetrustActiveGroups
    delete testWindow.OneTrust

    await TestBed.configureTestingModule({
      imports: [VideoEmbedComponent],
    }).compileComponents()

    fixture = TestBed.createComponent(VideoEmbedComponent)
  })

  afterEach(() => {
    delete testWindow.OnetrustActiveGroups
    delete testWindow.OneTrust
  })

  describe('once functional cookies are accepted', () => {
    beforeEach(() => acceptFunctionalCookies())

    it('loads no third-party frame until the visitor asks for one', () => {
      const element = render()

      expect(element.querySelector('iframe')).toBeNull()
      expect(element.querySelector('.video-play')).not.toBeNull()
    })

    it('names the play button after the video, not "Play"', () => {
      const button = render().querySelector('.video-play') as HTMLButtonElement
      expect(button.getAttribute('aria-label')).toBe(
        'Play video: What is ORCID?'
      )
    })

    it('shows the poster with the alt text the editor wrote', () => {
      const image = render().querySelector('img') as HTMLImageElement
      expect(image.getAttribute('alt')).toBe('A researcher at a laptop')
      expect(image.getAttribute('src')).toBe('/assets/img/poster.jpg')
    })

    it('mounts the player only after the button is pressed', () => {
      const element = render()
      ;(element.querySelector('.video-play') as HTMLButtonElement).click()
      fixture.detectChanges()

      const frame = element.querySelector('iframe') as HTMLIFrameElement
      expect(frame.getAttribute('src')).toBe(
        'https://player.vimeo.com/video/1198760040?dnt=1&title=0&autoplay=1'
      )
    })

    it('gives the frame the video own title plus a type hint', () => {
      const element = render()
      ;(element.querySelector('.video-play') as HTMLButtonElement).click()
      fixture.detectChanges()

      expect(
        (element.querySelector('iframe') as HTMLIFrameElement).getAttribute(
          'title'
        )
      ).toBe('What is ORCID? (video)')
    })

    it('never lets the frame autoplay on its own', () => {
      const element = render()
      ;(element.querySelector('.video-play') as HTMLButtonElement).click()
      fixture.detectChanges()

      const frame = element.querySelector('iframe') as HTMLIFrameElement
      expect(frame.getAttribute('allow')).toBe(
        'fullscreen; picture-in-picture; encrypted-media'
      )
      expect(frame.getAttribute('allow')).not.toContain('autoplay')
      expect(frame.getAttribute('referrerpolicy')).toBe(
        'strict-origin-when-cross-origin'
      )
      expect(frame.getAttribute('loading')).toBe('lazy')
    })

    it('moves focus into the player the visitor just opened', () => {
      const element = render()
      ;(element.querySelector('.video-play') as HTMLButtonElement).click()
      fixture.detectChanges()

      expect(document.activeElement).toBe(element.querySelector('iframe'))
    })

    it('renders no player at all for an id the provider would reject', () => {
      const element = render(video({ videoId: 'not-an-id' }))

      expect(element.querySelector('.video-play')).toBeNull()
      expect(element.querySelector('iframe')).toBeNull()
      expect(
        (element.querySelector('img') as HTMLImageElement).getAttribute('alt')
      ).toBe('A researcher at a laptop')
    })

    it('plays a YouTube video from the nocookie host', () => {
      const element = render(
        video({ provider: 'youtube', videoId: '1rZvFGLe7bg' })
      )
      ;(element.querySelector('.video-play') as HTMLButtonElement).click()
      fixture.detectChanges()

      expect(
        (element.querySelector('iframe') as HTMLIFrameElement).getAttribute(
          'src'
        )
      ).toBe(
        'https://www.youtube-nocookie.com/embed/1rZvFGLe7bg' +
          '?rel=0&modestbranding=1&cc_load_policy=1&autoplay=1'
      )
    })

    it('gives the frame the shape the editor chose', () => {
      const frame = render(video({ aspectRatio: '1:1' })).querySelector(
        '.video-frame'
      ) as HTMLElement
      expect(frame.style.aspectRatio).toBe('1 / 1')
    })

    it('offers the transcript', () => {
      const element = openTranscript(render())
      expect(transcriptText(element)).toContain('persistent identifier')
      expect(
        element.querySelectorAll('.video-transcript-paragraph').length
      ).toBe(2)
    })
  })

  describe('when functional cookies were never accepted', () => {
    it('shows the consent state instead of an empty frame', () => {
      const element = render()

      expect(element.querySelector('iframe')).toBeNull()
      expect(element.querySelector('.video-play')).toBeNull()
      expect(element.textContent).toContain('needs functional cookies')
      expect(
        (element.querySelector('a') as HTMLAnchorElement).getAttribute('href')
      ).toBe('https://vimeo.com/1198760040')
    })

    it('still offers the whole transcript', () => {
      const element = openTranscript(render())
      expect(transcriptText(element)).toContain('persistent identifier')
      expect(transcriptText(element)).toContain('whole career')
    })

    it('offers cookie settings only when a preference centre exists', () => {
      expect(render().querySelector('.consent-settings')).toBeNull()

      const toggle = jasmine.createSpy('ToggleInfoDisplay')
      testWindow.OneTrust = { ToggleInfoDisplay: toggle }
      const element = render()
      ;(element.querySelector('.consent-settings') as HTMLButtonElement).click()

      expect(toggle).toHaveBeenCalled()
    })

    it('swaps to the player facade when the visitor later accepts', () => {
      const element = render()
      expect(element.querySelector('.video-play')).toBeNull()

      acceptFunctionalCookies()
      window.dispatchEvent(new Event('OneTrustGroupsUpdated'))
      fixture.detectChanges()

      expect(element.querySelector('.video-play')).not.toBeNull()
      expect(element.querySelector('app-video-consent')).toBeNull()
    })
  })

  it('captions the video with its title', () => {
    acceptFunctionalCookies()
    expect(
      (render().querySelector('figcaption') as HTMLElement).textContent?.trim()
    ).toBe('What is ORCID?')
  })
})
